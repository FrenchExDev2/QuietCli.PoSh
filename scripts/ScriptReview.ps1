#requires -Version 7.6
function Get-QuietScriptReview {
    <#
    .SYNOPSIS
    Reviews every automation script and its declared effect boundary using the PowerShell AST.
    .PARAMETER WorkspaceRoot
    Repository containing scripts.
    #>
    param([string]$WorkspaceRoot)
    . (Join-Path $PSScriptRoot ScriptShouldProcess.ps1)
    $libraries=@('AgentDocuments','Bootstrap','Ci.Process','CiImages','Common','Gallery','GitHubCi','Monitor.Time','ReportPaths','ReportStreaming','ResourceDocumentation','Resources','RuntimeTargets','ScriptReview','ScriptShouldProcess','SourceIdentity','TestConfiguration','WorkflowDocumentation','WorkspaceProjects')
    $readOnly=@('Assert-CoreIntegrationEvidence','Assert-GalleryCheckpoint','Assert-PtyQualification','Show-ColdStartMatrixReport','Show-ColdStartReport','Test-GitHubWorkflowDocs','Test-Resources','Test-ScriptShouldProcess','Test-ScriptContracts','Watch-Tests','Watch-DotNetTests','Invoke-WorkspaceChecks')
    foreach($file in Get-ChildItem (Join-Path $WorkspaceRoot scripts) -Recurse -File|Where-Object Extension -In @('.ps1','.psm1')|Sort-Object FullName){
        $tokens=$null;$errors=$null;$ast=[Management.Automation.Language.Parser]::ParseFile($file.FullName,[ref]$tokens,[ref]$errors)
        if($errors.Count){throw ('ScriptReviewParseFailed: '+$file.Name)}
        $text=[IO.File]::ReadAllTextAsync($file.FullName,[Text.Encoding]::UTF8).GetAwaiter().GetResult()
        $mode=if($file.Extension -eq '.psm1' -or $file.BaseName -in $libraries){'Library'}elseif($file.Name -like '*.profile.ps1'){'ProfileDefinition'}elseif($file.BaseName -in $readOnly){'ReadOnly'}else{'Executable'}
        $kind=Get-QuietScriptShouldProcess $file.FullName
        if($kind -ceq 'Library'){$mode='Library'}
        $declared=$ast.ParamBlock -and @($ast.ParamBlock.Attributes|Where-Object {$_.TypeName.Name -ieq 'CmdletBinding' -and $_.Extent.Text -match 'SupportsShouldProcess'}).Count -gt 0
        if($declared -and $kind -ne 'ShouldProcess'){$kind='DelegatedShouldProcess'}
        $synopsis=[regex]::Match($text,'(?is)\.SYNOPSIS\s*\n(.*?)(?=\n\s*\.|#>)')
        $purpose=if($synopsis.Success){([regex]::Replace($synopsis.Groups[1].Value,'\s+',' ')).Trim()}else{'Provide '+$file.BaseName+' automation.'}
        if($purpose.Length -gt 220){$purpose=$purpose.Substring(0,217)+'...'}
        [pscustomobject]@{
            Path=[IO.Path]::GetRelativePath($WorkspaceRoot,$file.FullName).Replace('\','/')
            Purpose=$purpose
            Mode=$mode;PreviewContract=$kind
            GuardedFunctions=@($ast.FindAll({param($n)$n -is [Management.Automation.Language.FunctionDefinitionAst] -and $n.Body.Extent.Text -match 'SupportsShouldProcess'},$true)).Count
            NeedsGuard=$mode -ceq 'Executable' -and !$declared -and $kind -cne 'ShouldProcess'
        }
    }
}
function Get-QuietScriptReviewReadme {
    <#
    .SYNOPSIS
    Renders the complete preview/confirmation review and its explicit remaining boundaries.
    .PARAMETER WorkspaceRoot
    Repository being reviewed.
    #>
    param([string]$WorkspaceRoot)
    $entries=@(Get-QuietScriptReview $WorkspaceRoot)
    $lines=[Collections.Generic.List[string]]::new()
    foreach($line in @('# Script preview and confirmation review','','Generated by Sync-ScriptContracts.ps1. Every scripts/**/*.ps1 and *.psm1 is included; this is an API/effect-boundary review, not proof of arbitrary native tool reversibility. Purpose is read from comment-based help; objective headers and automatic objective announcements are not required.','','| Script | Boundary | Preview API | Guarded functions | Purpose |','| --- | --- | --- | ---: | --- |')){$lines.Add($line)}
    foreach($entry in $entries){$lines.Add('| '+$entry.Path+' | '+$entry.Mode+' | '+$entry.PreviewContract+' | '+$entry.GuardedFunctions+' | '+$entry.Purpose.Replace('|','&#124;')+' |')}
    $lines.Add('');$lines.Add('Executable entry points guard orchestration with the standard ShouldProcess API. Existing detailed per-operation guards are preserved. Newly upgraded entry points preview the whole operation; PlanOnly image planning remains available. Libraries delegate mutations to guarded callers; profile definitions contain data. Read-only monitors/checkers do not gain cosmetic confirmation prompts. Dependency preparation is independently guarded by Ensure-QuietResource.')
    $lines.Add('');$lines.Add('Static guard presence cannot prove that every future branch or external executable is safe. Runtime no-write tests, process/container ownership, explicit effects and publication checks remain required. Functions inside libraries that lack their own guard are not independently qualified for direct mutating use.')
    return (($lines -join "`n")+"`n")
}
