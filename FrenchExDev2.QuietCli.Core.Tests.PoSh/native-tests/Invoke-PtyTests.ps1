# Objectif : Compiler et exécuter les régressions C du PTY avec une fenêtre de suivi dédiée.
#requires -Version 7.6
<#
.SYNOPSIS
Builds native bridge unit tests with the pinned compiler and runs them in an existing Linux image.
.PARAMETER WorkspaceRoot
QuietCli2 monorepo root.
.PARAMETER Image
Existing local Linux x64 image; never pulled and run without network access.
.PARAMETER RunDirectory
Owned output directory, generated by the launcher when omitted.
.PARAMETER Worker
Internal background worker mode used by this launcher.
#>
[CmdletBinding()]param(
    [string]$WorkspaceRoot=(Resolve-Path (Join-Path $PSScriptRoot '../..')).Path,
    [string]$Image='localhost/quietcli2-debian-net11:2.56.0',
    [string]$RunDirectory,
    [switch]$Worker
)
$ErrorActionPreference='Stop'
. (Join-Path $WorkspaceRoot 'scripts/Common.ps1')
if(!$Worker){
    if(!$IsWindows){throw 'Launch from Windows for the required visible monitor.'}
    $RunDirectory=Join-Path $WorkspaceRoot ('artifacts/pty-tests/'+[guid]::NewGuid().ToString('N'))
    [void][IO.Directory]::CreateDirectory($RunDirectory)
    $runner=(Get-Command pwsh -CommandType Application|Select-Object -First 1).Source
    $process=Start-Process $runner -WindowStyle Hidden -PassThru -RedirectStandardOutput (Join-Path $RunDirectory 'worker.stdout.log') -RedirectStandardError (Join-Path $RunDirectory 'worker.stderr.log') -ArgumentList @('-File',('"'+$PSCommandPath+'"'),'-WorkspaceRoot',('"'+$WorkspaceRoot+'"'),'-Image',$Image,'-RunDirectory',('"'+$RunDirectory+'"'),'-Worker')
    $monitorPath=Join-Path $WorkspaceRoot 'scripts/Watch-Tests.ps1'
    $monitor=Start-Process $runner -WindowStyle Normal -PassThru -ArgumentList @('-File',('"'+$monitorPath+'"'),'-RunDirectory',('"'+$RunDirectory+'"'))
    "Monitor: pwsh -File `"$monitorPath`" -RunDirectory `"$RunDirectory`""
    $summary=Wait-WorkspaceWorker -Worker $process -Monitor $monitor -Runner $runner -RunDirectory $RunDirectory -WorkspaceRoot $WorkspaceRoot -TimeoutSeconds 900
    $summary.State
    if($summary.State.State -ne 'Success'){throw "PTY tests failed: $RunDirectory"}
    return
}
$containerAttempted=$false
$container='quietcli-pty-tests-'+[guid]::NewGuid().ToString('N')
$state=@{Project='FrenchExDev2.QuietCli.Core.PoSh';Task='Native PTY unit tests';Workspace=$WorkspaceRoot;ProjectDirectory=(Join-Path $WorkspaceRoot 'FrenchExDev2.QuietCli.Core.PoSh');Platform='linux-x64';State='Running';StartedUtc=[DateTimeOffset]::UtcNow.ToString('o');ProcessId=$PID;ContainerId=$container;Passed=0;Failed=0;Case='Compiling';Error=$null}
$status=Join-Path $RunDirectory 'status.json'
Write-WorkspaceJson $status $state
try{
    . (Join-Path $PSScriptRoot 'Hardening.ps1')
    $hardening=@(Assert-PtyHardening -WorkspaceRoot $WorkspaceRoot)
    Write-WorkspaceJson (Join-Path $RunDirectory 'hardening.json') $hardening
    $compiler=@(Get-ChildItem (Join-Path $WorkspaceRoot 'artifacts/toolchains') -Filter zig.exe -Recurse)
    if($compiler.Count -ne 1){throw 'Pinned compiler must already be available.'}
    $lock=Get-Content (Join-Path $WorkspaceRoot 'build/zig.lock.json') -Raw -Encoding utf8|ConvertFrom-Json
    $version=@{Text=''}
    $r=Invoke-CiProcess -FilePath $compiler[0].FullName -ArgumentList @('version') -State $version -OnOutput {param($e,$s)if($e.Stream -eq 'stdout'){$s.Text=$e.Text.Trim()}}
    if($r.Outcome -ne 'Success' -or $version.Text -cne $lock.Version){throw 'CompilerVersionMismatch'}
    $binary=Join-Path $RunDirectory 'pty-tests'
    $buildState=@{Lines=[Collections.Generic.List[string]]::new()}
    $build=Invoke-CiProcess -FilePath $compiler[0].FullName -ArgumentList @('cc','-target','x86_64-linux-musl','-std=c11','-O2','-Wall','-Wextra','-Werror','-fstack-protector-strong','-D_FORTIFY_SOURCE=2','-fPIE','-static','-pie','-Wl,-z,relro,-z,now','-pthread','-lutil',(Join-Path $PSScriptRoot 'pty-tests.c'),'-o',$binary) -TimeoutSeconds 600 -State $buildState -OnOutput {param($e,$s)if($s.Lines.Count -lt 30){$s.Lines.Add($e.Text)}}
    Write-WorkspaceJson (Join-Path $RunDirectory 'compiler.json') @{Outcome=$build.Outcome;Diagnostics=@($buildState.Lines)}
    if($build.Outcome -ne 'Success'){throw 'Native test compilation failed; see compiler.json'}
    $state.Case='Running native assertions';Write-WorkspaceJson $status $state
    $evidence=@{Cases=[Collections.Generic.List[string]]::new();State=$state;Status=$status}
    $containerAttempted=$true
    $r=Invoke-CiProcess -FilePath podman -ArgumentList @('run','--pull=never','--rm','--network=none','--name',$container,'--volume',($RunDirectory+':/tests:ro'),'--volume',($RunDirectory+':/evidence:rw'),'--env','QUIETCLI_PTY_EVIDENCE=/evidence','--entrypoint','/tests/pty-tests',$Image) -TimeoutSeconds 60 -State $evidence -OnOutput {
        param($e,$s)
        if($s.Cases.Count -ge 100){throw 'Unexpected test output volume'}
        $s.Cases.Add($e.Text)
        if($e.Text.StartsWith('PASS ')){$s.State.Passed++}
        elseif($e.Text.StartsWith('FAIL ')){$s.State.Failed++}
        $s.State.Case=$e.Text;Write-WorkspaceJson $s.Status $s.State
    }
    if($r.Outcome -eq 'Success'){$containerAttempted=$false} # Successful --rm already removed the owned container.
    Write-WorkspaceJson (Join-Path $RunDirectory 'assertions.json') @{Outcome=$r.Outcome;Cases=@($evidence.Cases)}
    if($r.Outcome -ne 'Success' -or $state.Failed -or $state.Passed -lt 43){throw 'Native PTY assertions failed or suite incomplete.'}
    $state.State='Success'
}catch{$state.State='Failed';$state.Failed++;$state.Error=$_.ToString()}
finally{
    # Remove only this worker's named container, including after a timeout.
    if($containerAttempted){
    $cleanup=Invoke-CiProcess -FilePath podman -ArgumentList @('rm','--force','--ignore',$container) -TimeoutSeconds 15 -OnOutput {param($e,$s)}
    if($cleanup.Outcome -ne 'Success'){$state.State='Failed';$state.Failed++;$state.Error+='; Owned container cleanup failed'}
    }
    $state.FinishedUtc=[DateTimeOffset]::UtcNow.ToString('o')
    Write-WorkspaceJson (Join-Path $RunDirectory 'summary.json') @{State=$state}
    Write-WorkspaceJson $status $state
}
if($state.State -ne 'Success'){exit 1}
