function Import-QuietRecallDevelopment {
    <#
    .SYNOPSIS
    Loads the source-verified companion assembly compatible with the current CLR.
    #>
    $workspace=Split-Path $PSScriptRoot -Parent
    $framework=if([Environment]::Version.Major -ge 11){'net11.0'}else{'net10.0'}
    $output='FrenchExDev2.QuietCli.Core.Tests.PoSh/lib/recall-tools/'+$framework
    $directory=Join-Path $PSScriptRoot ('lib/recall-tools/'+$framework)
    if(Test-Path -LiteralPath (Join-Path $workspace 'scripts/Common.ps1')){
        . (Join-Path $workspace 'scripts/Common.ps1')
        $null=Test-QuietBuildManifest -WorkspaceRoot $workspace -Output $output
    }else{
        $manifest=[IO.File]::ReadAllTextAsync((Join-Path $directory 'build-manifest.json')).GetAwaiter().GetResult()|ConvertFrom-Json
        if($manifest.SchemaVersion -ne 1 -or $manifest.Project -cne 'FrenchExDev2.QuietCli.Core.Tests.PoSh/recall-tools/QuietCli.Recall.Tools.csproj' -or @($manifest.Binaries|Where-Object Path -CEQ 'QuietCli.Recall.Tools.dll').Count -ne 1){throw 'RecallToolsBuildIdentityInvalid'}
        foreach($binary in $manifest.Binaries){
            if([string]::IsNullOrWhiteSpace($binary.Path) -or $binary.Path -in @('.','..') -or [IO.Path]::GetFileName($binary.Path) -cne $binary.Path){throw 'RecallToolsUnsafePath'}
            $path=Join-Path $directory $binary.Path
            if(!(Test-Path -LiteralPath $path) -or (Get-Item -LiteralPath $path).Length -ne $binary.Bytes -or (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash -cne $binary.SHA256){throw 'RecallToolsBinaryIntegrityFailed'}
        }
    }
    $assembly=[Reflection.Assembly]::LoadFrom((Join-Path $directory 'QuietCli.Recall.Tools.dll'))
    if(![StringComparer]::OrdinalIgnoreCase.Equals($assembly.Location,[IO.Path]::GetFullPath((Join-Path $directory 'QuietCli.Recall.Tools.dll')))){throw 'RecallToolsAlreadyLoadedFromAnotherModule'}
}
function Compare-QuietRecallAnalysis {
    <#
    .SYNOPSIS
    Compares two fresh offline analyses and their independently measured costs.
    .PARAMETER InputObject
    Result or immutable capture.
    .PARAMETER First
    First analyzer options: Output, Complete and optional decoding overrides.
    .PARAMETER Second
    Second analyzer options.
    .PARAMETER DataFactory
    Creates fresh business state separately for each analyzer.
    .PARAMETER Projection
    Optional stable projection of each result for comparison.
    .PARAMETER AllowPartial
    Explicitly accepts incomplete retention.
    #>
    [CmdletBinding()]param([Parameter(Mandatory)]$InputObject,[Parameter(Mandatory)][hashtable]$First,[Parameter(Mandatory)][hashtable]$Second,[scriptblock]$DataFactory={@{}},[scriptblock]$Projection={param($r) $r.Data},[switch]$AllowPartial)
    $results=@(foreach($options in @($First,$Second)){
        if($options.ContainsKey('Data') -or $options.ContainsKey('State') -or $options.ContainsKey('InputObject')){throw 'RecallComparisonRequiresFreshState'}
        Invoke-QuietRecall -InputObject $InputObject @options -Data (& $DataFactory) -State @{} -AllowPartial:$AllowPartial
    })
    $a=& $Projection $results[0];$b=& $Projection $results[1]
    # JSON is an explicit comparison projection, never an AsObject measurement.
    $left=ConvertTo-Json -InputObject $a -Depth 64 -Compress
    $right=ConvertTo-Json -InputObject $b -Depth 64 -Compress
    Import-QuietRecallDevelopment
    $equal=[FrenchExDev2.QuietCli.RecallDevelopment]::EquivalentJson($left,$right)
    [pscustomobject]@{Equal=$equal;First=$results[0];Second=$results[1];Difference=$(if(!$equal){[pscustomobject]@{First=$a;Second=$b}}else{$null});DiagnosticsEqual=((ConvertTo-Json -InputObject $results[0].Error -Depth 16 -Compress) -ceq (ConvertTo-Json -InputObject $results[1].Error -Depth 16 -Compress))}
}
function Export-QuietRecallFixture {
    <#
    .SYNOPSIS
    Exports a new fixture directory and an independently failing expectation template.
    .PARAMETER InputObject
    Result or immutable capture. Export preserves the supplied bytes exactly.
    .PARAMETER Path
    New fixture directory.
    #>
    [CmdletBinding()]param([Parameter(Mandatory)]$InputObject,[Parameter(Mandatory)][string]$Path)
    $destination=$ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Path)
    if([IO.Directory]::Exists($destination) -or [IO.File]::Exists($destination)){throw 'RecallFixtureDestinationExists'}
    [void][IO.Directory]::CreateDirectory($destination)
    Export-QuietRecall -InputObject $InputObject -Path (Join-Path $destination 'capture.qrecall')
    $template=@'
# Import the fixture with an explicit finite budget, then define independent business assertions.
# Never replace these expectations with a snapshot generated by the analyzer under test.
throw 'RecallFixtureExpectationsRequired'
'@
    [void][IO.File]::WriteAllTextAsync((Join-Path $destination 'Regression.Tests.ps1'),$template.Replace("`r`n","`n")+"`n",[Text.UTF8Encoding]::new($false)).GetAwaiter().GetResult()
    return $destination
}
function Reduce-QuietRecall {
    <#
    .SYNOPSIS
    Removes events under a bounded explicit failure predicate; does not claim minimality.
    .PARAMETER InputObject
    Capture or native result.
    .PARAMETER FailurePredicate
    Must return exactly one Boolean; must return promptly and use no native execution.
    .PARAMETER MaxAttempts
    Maximum predicate calls including baseline.
    .PARAMETER MaxSeconds
    Time budget checked between cooperative predicate calls.
    #>
    [CmdletBinding()]param([Parameter(Mandatory)]$InputObject,[Parameter(Mandatory)][scriptblock]$FailurePredicate,[ValidateRange(1,100000)][int]$MaxAttempts=100,[ValidateRange(0.01,3600)][double]$MaxSeconds=30)
    $capture=if($InputObject.PSObject.Properties['Recall']){$InputObject.Recall}else{$InputObject}
    if($capture.GetType().FullName -ne 'FrenchExDev2.QuietCli.RecallCapture'){throw 'RecallCaptureRequired'}
    Import-QuietRecallDevelopment
    $callback=[Func[FrenchExDev2.QuietCli.RecallCapture,bool]]{
        param($candidate)
        $values=@(& $FailurePredicate $candidate)
        if($values.Count -ne 1 -or $values[0] -isnot [bool]){throw 'RecallPredicateMustReturnBoolean'}
        return $values[0]
    }.GetNewClosure()
    return [FrenchExDev2.QuietCli.RecallDevelopment]::ReduceAsync($capture,$callback,$MaxAttempts,$MaxSeconds).GetAwaiter().GetResult()
}
