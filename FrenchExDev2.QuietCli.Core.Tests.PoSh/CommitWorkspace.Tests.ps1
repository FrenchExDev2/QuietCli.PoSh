function New-QuietCommitWorkspaceFixture {
    <#
    .SYNOPSIS
    Creates a real Git integration fixture already satisfying Commit-Workspace.ps1's own
    documentation-sync gates, with one baseline commit in place.
    .DESCRIPTION
    Ships exactly one business module (so Update-WorkspaceLock.ps1/Sync-Credits.ps1 have something
    to discover) and one documented script (scripts/Get-Tracked.ps1 + docs/scripts/Get-Tracked.md), with
    CREDITS.md, docs/scripts/README.md and every credits block generated by the real
    Sync-Credits.ps1/Sync-ScriptsReadme.ps1/Sync-DocsCredits.ps1 scripts themselves (via -Apply), so
    this fixture never duplicates their own expected-content logic.
    .PARAMETER Root
    Owned fixture root; a fresh subdirectory is created under it.
    .PARAMETER RealScriptsPath
    This repository's real scripts/ directory, used only to run the three Sync-*.ps1 gate scripts
    against the fixture once during setup.
    #>
    param([Parameter(Mandatory)][string]$Root, [Parameter(Mandatory)][string]$RealScriptsPath)
    $path = Join-Path $Root ('commit-' + [guid]::NewGuid().ToString('N').Substring(0, 8))
    [void][IO.Directory]::CreateDirectory($path)
    foreach ($arguments in @(
        @('init', '--initial-branch=main'),
        @('config', 'user.name', 'QuietCli2 Test'),
        @('config', 'user.email', 'quietcli2@example.invalid'),
        @('config', 'commit.gpgsign', 'false'),
        @('config', 'core.autocrlf', 'false')
    )) {
        & git -C $path @arguments *>$null
        if ($LASTEXITCODE -ne 0) { throw ('CommitWorkspaceFixtureGitFailed: ' + ($arguments -join ' ')) }
    }
    $utf8 = [Text.UTF8Encoding]::new($false)
    # The real shared registry also validates an inert Core catalogue in exported indexes.
    $testDirectory=Join-Path $path 'FrenchExDev2.QuietCli.Core.Tests.PoSh'
    [void][IO.Directory]::CreateDirectory($testDirectory)
    [IO.File]::WriteAllText((Join-Path $testDirectory 'FrenchExDev2.QuietCli.Core.Tests.PoSh.psd1'),"@{ ModuleVersion='1.0.0';RootModule='FrenchExDev2.QuietCli.Core.Tests.PoSh.psm1';PrivateData=@{QuietCli=@{TestCatalogue=@{Runner='Invoke-QuietCoreTests';Sources=@()}}} }`n",$utf8)
    [IO.File]::WriteAllText((Join-Path $testDirectory 'LICENSE_CREDITS.md'),"## Fixture`n`nInert classification fixture ships no dependency.`n",$utf8)
    $catalogue=@'
function Invoke-QuietCoreTests {
    <#
    .SYNOPSIS
    Declares one inert classification fixture; commit checks never execute it.
    #>
    $cases=[ordered]@{}
    $cases['fixture']={}
    $caseMetadata=@{'fixture'=@{TestKind='Unit';Dependencies=@()}}
}
'@
    [IO.File]::WriteAllText((Join-Path $testDirectory 'FrenchExDev2.QuietCli.Core.Tests.PoSh.psm1'),($catalogue+"`n"),$utf8)
    Copy-Item -LiteralPath (Join-Path (Split-Path $RealScriptsPath -Parent) 'global.json') -Destination $path
    $moduleDirectory = Join-Path $path 'FrenchExDev2.QuietCli.Core.PoSh'
    [void][IO.Directory]::CreateDirectory($moduleDirectory)
    [void][IO.File]::WriteAllTextAsync((Join-Path $moduleDirectory 'FrenchExDev2.QuietCli.Core.PoSh.psd1'), "@{ ModuleVersion = '1.0.0' }`n", $utf8).GetAwaiter().GetResult()
    [void][IO.Directory]::CreateDirectory((Join-Path $moduleDirectory 'engine'))
    [void][IO.Directory]::CreateDirectory((Join-Path $moduleDirectory 'resources'))
    Copy-Item -LiteralPath (Join-Path (Split-Path $RealScriptsPath -Parent) 'FrenchExDev2.QuietCli.Core.PoSh/engine/QuietCli.Engine.csproj') -Destination (Join-Path $moduleDirectory 'engine')
    [void][IO.File]::WriteAllTextAsync((Join-Path $moduleDirectory 'resources/dependencies.lock.json'), "{`"Files`":[],`"Packages`":[]}`n", $utf8).GetAwaiter().GetResult()
    [void][IO.File]::WriteAllTextAsync((Join-Path $moduleDirectory 'LICENSE_CREDITS.md'), "## Fixture`n`nFixture module ships no third-party native dependency.`n", $utf8).GetAwaiter().GetResult()
    $scriptsDirectory = Join-Path $path 'scripts'
    $docsScriptsDirectory = Join-Path $path 'docs/scripts'
    [void][IO.Directory]::CreateDirectory($scriptsDirectory)
    [void][IO.Directory]::CreateDirectory($docsScriptsDirectory)
    [void][IO.File]::WriteAllTextAsync((Join-Path $scriptsDirectory 'Get-Tracked.ps1'), "# Fixture script, documented below.`n", $utf8).GetAwaiter().GetResult()
    [void][IO.File]::WriteAllTextAsync((Join-Path $docsScriptsDirectory 'Get-Tracked.md'), "# Get-Tracked.ps1`n`nFixture doc.`n", $utf8).GetAwaiter().GetResult()
    # Include the real gate and its doc: snapshots must not change the generator's own membership.
    Copy-Item -LiteralPath (Join-Path $RealScriptsPath 'Sync-ScriptsReadme.ps1') -Destination $scriptsDirectory
    Copy-Item -LiteralPath (Join-Path (Split-Path $RealScriptsPath -Parent) 'docs/scripts/Sync-ScriptsReadme.md') -Destination $docsScriptsDirectory
    [void][IO.Directory]::CreateDirectory([IO.Path]::Combine($scriptsDirectory,'lib'))
    [void][IO.Directory]::CreateDirectory([IO.Path]::Combine($docsScriptsDirectory,'lib'))
    Copy-Item -LiteralPath ([IO.Path]::Combine($RealScriptsPath,'lib/Sync-ScriptsReadme.psm1')) -Destination ([IO.Path]::Combine($scriptsDirectory,'lib'))
    Copy-Item -LiteralPath ([IO.Path]::Combine([IO.Path]::GetDirectoryName($RealScriptsPath),'docs/scripts/lib/Sync-ScriptsReadme.md')) -Destination ([IO.Path]::Combine($docsScriptsDirectory,'lib'))
    [void][IO.Directory]::CreateDirectory((Join-Path $path build))
    Write-WorkspaceJson (Join-Path $path build/script-shouldprocess.json) @{SchemaVersion=1;LegacyPaths=@();ReadOnlyExceptions=@()}
    $null=& (Join-Path $RealScriptsPath 'Sync-GitHubWorkflowsReadme.ps1') -WorkspaceRoot $path -Apply
    $null=& (Join-Path $RealScriptsPath 'Sync-ResourcesReadme.ps1') -WorkspaceRoot $path -Apply
    $null=& (Join-Path $RealScriptsPath 'Sync-ScriptContracts.ps1') -WorkspaceRoot $path -Apply
    # Order matters: Sync-Credits writes CREDITS.md (required by Sync-DocsCredits), Sync-ScriptsReadme
    # writes docs/scripts/README.md (already carrying its own compliant credits block), and only then
    # does Sync-DocsCredits need to add the block to the hand-written Get-Tracked.md.
    $null = & (Join-Path $RealScriptsPath 'Sync-Credits.ps1') -WorkspaceRoot $path -CreditsPath (Join-Path $path 'CREDITS.md') -Apply
    $null = & (Join-Path $RealScriptsPath 'Sync-ScriptsReadme.ps1') -ScriptsPath $scriptsDirectory -DocsPath $docsScriptsDirectory -Apply
    $null = & (Join-Path $RealScriptsPath 'Sync-DocsCredits.ps1') -DocsPath (Join-Path $path 'docs') -RootPath $path -CreditsPath (Join-Path $path 'CREDITS.md') -Apply
    & git -C $path add -A *>$null
    & git -C $path commit -m 'fixture baseline' *>$null
    if ($LASTEXITCODE -ne 0) { throw 'CommitWorkspaceFixtureBaselineCommitFailed' }
    return $path
}

function Get-QuietCommitWorkspaceHeadRevision {
    <#
    .SYNOPSIS
    Reads one fixture's current HEAD revision, independently of Commit-Workspace.ps1 itself.
    .PARAMETER Path
    Disposable fixture repository.
    #>
    param([Parameter(Mandatory)][string]$Path)
    (& git -C $Path rev-parse HEAD).Trim()
}

function Test-QuietByteCountParsing {
    <#
    .SYNOPSIS
    Checks Common.ps1's ConvertTo-QuietByteCount against decimal and binary units, a bare integer
    and invalid input, independently of any fixture repository.
    #>
    foreach ($case in @(
        @{ Size = '750'; Expected = 750L },
        @{ Size = '500KB'; Expected = 500000L },
        @{ Size = '1 MiB'; Expected = 1048576L },
        @{ Size = '2GiB'; Expected = 2147483648L },
        @{ Size = '1TB'; Expected = 1000000000000L },
        @{ Size = '0'; Expected = 0L }
    )) {
        $actual = ConvertTo-QuietByteCount $case.Size
        if ($actual -ne $case.Expected) { throw ("ByteCountParseFailed: size=$($case.Size) expected=$($case.Expected) actual=$actual") }
    }
    foreach ($invalid in @('abc', '-5', '5XB')) {
        $threw = $false
        try { $null = ConvertTo-QuietByteCount $invalid } catch { $threw = $_.Exception.Message -ceq ('QuietByteCountInvalid: ' + $invalid) }
        if (!$threw) { throw ("ByteCountParseAcceptedInvalidInput: $invalid") }
    }
    # An empty string never reaches the function body - PowerShell's own Mandatory binding rejects
    # it first, with a locale-dependent message, so only presence of a failure is asserted here.
    $threw = $false
    try { $null = ConvertTo-QuietByteCount '' } catch { $threw = $true }
    if (!$threw) { throw 'ByteCountParseAcceptedEmptyString' }
}

function Test-QuietCommitWorkspace {
    <#
    .SYNOPSIS
    Checks Commit-Workspace.ps1's documentation-sync gates, script/doc drift warning, binary/
    oversized-file sniffer and -WhatIf contract, and confirms it still refreshes the lock, stages
    once, commits exactly once and never configures a remote - including under targeted mutants of
    the gating logic.
    .DESCRIPTION
    Exercises the real script against disposable fixture repositories only; this never runs against
    the actual monorepo checkout. It does not re-verify the three Sync-*.ps1 gates' own internal
    correctness (missing/stale detection, generated content) - only that Commit-Workspace.ps1 wires
    each of them in, honors its own -No* override switches, and that the drift and file-sniffer
    warnings fire for exactly the right paths without ever blocking the commit. Also checks
    Common.ps1's ConvertTo-QuietByteCount in isolation (no fixture repository needed).
    .PARAMETER WorkspaceRoot
    Real repository containing scripts/Commit-Workspace.ps1 and its sync-gate dependencies.
    .PARAMETER RunDirectory
    Owned temporary fixtures and the mutation report.
    #>
    param([string]$WorkspaceRoot, [string]$RunDirectory, [int]$MaxConcurrency=0, [string]$CandidatePath)
    if(!$MaxConcurrency){
        $configured=0
        if($env:QUIETCLI_TEST_MAX_CONCURRENCY -and ![int]::TryParse($env:QUIETCLI_TEST_MAX_CONCURRENCY,[ref]$configured)){throw 'TestMaxConcurrencyInvalid'}
        $MaxConcurrency=if($configured){$configured}else{[Math]::Min(4,[Math]::Max(1,[Environment]::ProcessorCount))}
    }
    if($MaxConcurrency -lt 1 -or $MaxConcurrency -gt 32){throw 'TestMaxConcurrencyOutOfRange'}
    $realScripts = Join-Path $WorkspaceRoot 'scripts'
    $sourcePath = Join-Path $realScripts 'Commit-Workspace.ps1'
    $source = [IO.File]::ReadAllTextAsync(([IO.Path]::Combine($realScripts,'lib/Commit-Workspace.psm1')), [Text.Encoding]::UTF8).GetAwaiter().GetResult()
    $fixtureRoot = Join-Path $RunDirectory 'commit-workspace'
    [void][IO.Directory]::CreateDirectory($fixtureRoot)
    $utf8 = [Text.UTF8Encoding]::new($false)

    $verify = {
        param($candidate, $fixtureRoot, $realScripts, $utf8)

        # A: the default run refreshes the lock, stages everything, commits exactly once and never
        # configures a remote of its own.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        $before = Get-QuietCommitWorkspaceHeadRevision $fixture
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'tracked.txt'), 'v1', $utf8).GetAwaiter().GetResult()
        $null = & $candidate -Message 'Add tracked file' -WorkspaceRoot $fixture
        $after = Get-QuietCommitWorkspaceHeadRevision $fixture
        if ($after -ceq $before) { throw 'DefaultRunDidNotCommit' }
        if (!(Test-Path -LiteralPath (Join-Path $fixture 'repositories.lock.json'))) { throw 'LockWasNotRefreshedBeforeCommit' }
        if (@(& git -C $fixture status --porcelain).Count) { throw 'WorkingTreeNotFullyStaged' }
        if (@(& git -C $fixture remote).Count) { throw 'CommitWorkspaceMustNeverConfigureARemote' }
        if ([int](& git -C $fixture rev-list --count HEAD) -ne 2) { throw 'MustCommitExactlyOnce' }

        # B: -WhatIf refreshes nothing, stages nothing and commits nothing.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        $before = Get-QuietCommitWorkspaceHeadRevision $fixture
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'tracked.txt'), 'v1', $utf8).GetAwaiter().GetResult()
        try{$null = & $candidate -Message 'Preview' -WorkspaceRoot $fixture -WhatIf}
        catch{
            if($_.Exception.Message -match '^Workspace operation failed: git \(Failed\)'){throw 'WhatIfAttemptedNativeMutation'}
            throw
        }
        $after = Get-QuietCommitWorkspaceHeadRevision $fixture
        if ($after -cne $before) { throw 'WhatIfMustNotCommit' }
        if (Test-Path -LiteralPath (Join-Path $fixture 'repositories.lock.json')) { throw 'WhatIfMustNotRefreshTheLock' }
        if (@(& git -C $fixture status --porcelain) -cnotcontains '?? tracked.txt') { throw 'WhatIfMustNotStage' }

        # B2: -NoAll commits the prepared index, retaining partial staging and unrelated work.
        foreach($name in @('selected.txt','selected file.txt','selected-é.txt')){
            $fixture=New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
            $selected=Join-Path $fixture $name
            [void][IO.File]::WriteAllTextAsync($selected,"selected content`n",$utf8).GetAwaiter().GetResult()
            $null=& (Join-Path $realScripts 'Update-WorkspaceLock.ps1') -WorkspaceRoot $fixture
            & git -C $fixture add -- $name repositories.lock.json
            if($LASTEXITCODE -ne 0){throw 'NoAllFixtureStagingFailed'}
            $before=Get-QuietCommitWorkspaceHeadRevision $fixture
            $lockHash=(Get-FileHash (Join-Path $fixture 'repositories.lock.json')).Hash
            [void][IO.File]::WriteAllTextAsync($selected,"unstaged content`n",$utf8).GetAwaiter().GetResult()
            [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'scripts/Unselected.ps1'),"# Unfinished, not selected or documented.`n",$utf8).GetAwaiter().GetResult()
            $indexHash=(Get-FileHash (Join-Path $fixture '.git/index')).Hash
            $null=& $candidate -Message 'Preview selected index' -WorkspaceRoot $fixture -NoAll -WhatIf
            if((Get-QuietCommitWorkspaceHeadRevision $fixture) -cne $before -or
                (Get-FileHash (Join-Path $fixture '.git/index')).Hash -cne $indexHash){throw 'NoAllWhatIfChangedTheIndexOrHead'}
            $null=& $candidate -Message 'Commit selected index' -WorkspaceRoot $fixture -NoAll
            if((Get-FileHash (Join-Path $fixture 'repositories.lock.json')).Hash -cne $lockHash){throw 'NoAllWorkingTreeLockChanged'}
            $committed=@(& git -C $fixture show ('HEAD:'+$name)) -join "`n"
            if($committed -cne 'selected content'){throw 'NoAllIncludedUnstagedContent'}
            if(@(& git -C $fixture ls-tree --name-only HEAD scripts/Unselected.ps1).Count){throw 'NoAllIncludedUnselectedFile'}
            if((Get-Content -LiteralPath $selected -Raw -Encoding utf8) -cne "unstaged content`n"){throw 'NoAllOverwroteUnstagedContent'}
            if(@(& git -C $fixture diff --cached --name-only).Count -or [int](& git -C $fixture rev-list --count HEAD) -ne 2){throw 'NoAllMustCommitPreparedIndexExactlyOnce'}
        }

        $fixture=New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        $rejected=$false
        try{$null=& $candidate -Message 'Empty index' -WorkspaceRoot $fixture -NoAll}catch{$rejected=$_.Exception.Message -ceq 'CommitWorkspaceNothingStaged'}
        if(!$rejected){throw 'NoAllEmptyIndexAccepted'}

        # B3: malformed or stale staged source locks fail before commit and never change the index.
        foreach($damage in @('root-digest','project-digest','duplicate-project','schema')){
            $fixture=New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
            $null=& (Join-Path $realScripts 'Update-WorkspaceLock.ps1') -WorkspaceRoot $fixture
            $lockPath=Join-Path $fixture 'repositories.lock.json'
            $lock=Get-Content -LiteralPath $lockPath -Raw -Encoding utf8|ConvertFrom-Json
            switch($damage){
                root-digest {$lock.Repository.SourceSHA256='0'*64}
                project-digest {$lock.Projects[0].SourceSHA256='0'*64}
                duplicate-project {$lock.Projects+=,$lock.Projects[0]}
                schema {$lock.SchemaVersion=99}
            }
            [void][IO.File]::WriteAllTextAsync($lockPath,($lock|ConvertTo-Json -Depth 10)+"`n",$utf8).GetAwaiter().GetResult()
            & git -C $fixture add -- repositories.lock.json
            $before=Get-QuietCommitWorkspaceHeadRevision $fixture
            $indexHash=(Get-FileHash (Join-Path $fixture '.git/index')).Hash
            $rejected=$false
            try{$null=& $candidate -Message 'Reject damaged index lock' -WorkspaceRoot $fixture -NoAll}catch{$rejected=$_.Exception.Message -ceq 'CommitWorkspaceStagedLockMismatch'}
            if(!$rejected -or (Get-QuietCommitWorkspaceHeadRevision $fixture) -cne $before -or (Get-FileHash (Join-Path $fixture '.git/index')).Hash -cne $indexHash){throw "NoAllDamagedLockAcceptedOrIndexChanged: $damage"}
        }

        # B4: gates inspect staged documentation even when the working copy has already fixed it.
        $fixture=New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        $docPath=Join-Path $fixture 'docs/scripts/Get-Tracked.md'
        $goodDoc=Get-Content -LiteralPath $docPath -Raw -Encoding utf8
        $missingCredits=[regex]::Replace($goodDoc,'(?s)<!-- credits:begin -->.*?<!-- credits:end -->','')
        [void][IO.File]::WriteAllTextAsync($docPath,$missingCredits,$utf8).GetAwaiter().GetResult()
        $null=& (Join-Path $realScripts 'Update-WorkspaceLock.ps1') -WorkspaceRoot $fixture
        & git -C $fixture add -- docs/scripts/Get-Tracked.md repositories.lock.json
        [void][IO.File]::WriteAllTextAsync($docPath,$goodDoc,$utf8).GetAwaiter().GetResult()
        $before=Get-QuietCommitWorkspaceHeadRevision $fixture
        $rejected=$false
        try{$null=& $candidate -Message 'Reject staged documentation gap' -WorkspaceRoot $fixture -NoAll}catch{$rejected=$_.Exception.Message -match 'Credits'}
        if(!$rejected -or (Get-QuietCommitWorkspaceHeadRevision $fixture) -cne $before){throw 'NoAllStagedDocumentationGateBypassed'}

        # C: a missing script doc blocks the default run, and is skippable with its own -No* switch
        # or with the convenience -NoSyncChecks.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'scripts/Get-Undocumented.ps1'), '# no matching doc', $utf8).GetAwaiter().GetResult()
        $before = Get-QuietCommitWorkspaceHeadRevision $fixture
        $rejected = $false; $message = $null
        try { $null = & $candidate -Message 'Should be rejected' -WorkspaceRoot $fixture } catch { $rejected = $true; $message = $_.Exception.Message }
        if (!$rejected -or $message -notmatch '^ScriptsDocsMissing') { throw 'MissingScriptDocGateDidNotBlock' }
        if ((Get-QuietCommitWorkspaceHeadRevision $fixture) -cne $before) { throw 'RejectedGateMustNotCommit' }
        $null = & $candidate -Message 'Skip both script documentation gates' -WorkspaceRoot $fixture -NoScriptsReadmeCheck -NoScriptContractsCheck
        if ((Get-QuietCommitWorkspaceHeadRevision $fixture) -ceq $before) { throw 'NoScriptsReadmeCheckDidNotAllowTheCommit' }

        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'scripts/Get-Undocumented.ps1'), '# no matching doc', $utf8).GetAwaiter().GetResult()
        $before = Get-QuietCommitWorkspaceHeadRevision $fixture
        $null = & $candidate -Message 'Skip every sync gate' -WorkspaceRoot $fixture -NoSyncChecks
        if ((Get-QuietCommitWorkspaceHeadRevision $fixture) -ceq $before) { throw 'NoSyncChecksDidNotAllowTheCommit' }

        # D: a script changed without its mirrored doc warns, but never blocks; the warning is
        # overridable on its own.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::AppendAllTextAsync((Join-Path $fixture 'scripts/Get-Tracked.ps1'), "# Fixture script, changed`n", $utf8).GetAwaiter().GetResult()
        $warnings = @(& $candidate -Message 'Drift check' -WorkspaceRoot $fixture 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match '^ScriptDocDrift: scripts/Get-Tracked\.ps1' }).Count -ne 1) { throw 'ScriptDocDriftWarningMissing' }

        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::AppendAllTextAsync((Join-Path $fixture 'scripts/Get-Tracked.ps1'), "# Fixture script, changed`n", $utf8).GetAwaiter().GetResult()
        $warnings = @(& $candidate -Message 'Drift check overridden' -WorkspaceRoot $fixture -NoScriptDocDriftWarning 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match '^ScriptDocDrift:' }).Count) { throw 'NoScriptDocDriftWarningDidNotSilenceIt' }

        # D2 (property): the warning fires for exactly the changed, undocumented script about to be
        # committed, never for an untouched, already-documented one, across randomly named scripts.
        $random = [Random]::new(97120)
        for ($round = 0; $round -lt 12; $round++) {
            $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
            $driftedName = 'Get-Drift' + $random.Next(10000, 99999) + '.ps1'
            [void][IO.File]::WriteAllTextAsync((Join-Path $fixture ('scripts/' + $driftedName)), '# undocumented and about to be committed', $utf8).GetAwaiter().GetResult()
            $warnings = @(& $candidate -Message 'Property round' -WorkspaceRoot $fixture -NoScriptsReadmeCheck -NoScriptContractsCheck 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
            $matching = @($warnings | Where-Object { $_.Message -match [regex]::Escape('scripts/' + $driftedName) })
            if ($matching.Count -ne 1) { throw ("ScriptDocDriftPropertyFailed: seed=97120 round=$round name=$driftedName") }
            if (@($warnings | Where-Object { $_.Message -match 'scripts/Get-Tracked\.ps1' }).Count) { throw "ScriptDocDriftFalsePositiveOnUnchangedDocumentedScript: round=$round" }
        }

        # E: an untracked file containing a NUL byte, not declared binary in .gitattributes, is
        # reported and the commit still succeeds (non-blocking).
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::WriteAllBytesAsync((Join-Path $fixture 'blob.bin'), [byte[]]@(66, 76, 0, 79, 66)).GetAwaiter().GetResult()
        $before = Get-QuietCommitWorkspaceHeadRevision $fixture
        $warnings = @(& $candidate -Message 'Binary sniffer' -WorkspaceRoot $fixture 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match '^CommitFileSniffer: blob\.bin \(binary content\)' }).Count -ne 1) { throw 'CommitFileSnifferBinaryWarningMissing' }
        if ((Get-QuietCommitWorkspaceHeadRevision $fixture) -ceq $before) { throw 'CommitFileSnifferMustNotBlockCommit' }

        # F: a file declared binary in .gitattributes produces no sniffer warning even though it
        # contains a NUL byte.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::AppendAllTextAsync((Join-Path $fixture '.gitattributes'), "*.exempt binary`n", $utf8).GetAwaiter().GetResult()
        [void][IO.File]::WriteAllBytesAsync((Join-Path $fixture 'blob.exempt'), [byte[]]@(66, 76, 0, 79, 66)).GetAwaiter().GetResult()
        $warnings = @(& $candidate -Message 'Exempted binary' -WorkspaceRoot $fixture 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match 'CommitFileSniffer' }).Count) { throw 'CommitFileSnifferExemptionBypassed' }

        # G: a plain-text file over the (test-supplied, small) MaxChangedFileSize threshold is
        # reported with a size-based reason; -NoCommitFileSnifferWarning silences it entirely.
        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'large.txt'), ('x' * 200), $utf8).GetAwaiter().GetResult()
        $warnings = @(& $candidate -Message 'Oversized file' -WorkspaceRoot $fixture -MaxChangedFileSize 100 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match '^CommitFileSniffer: large\.txt \(size \d+ bytes exceeds 100 bytes\)' }).Count -ne 1) { throw 'CommitFileSnifferSizeWarningMissing' }

        $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
        [void][IO.File]::WriteAllTextAsync((Join-Path $fixture 'large.txt'), ('x' * 200), $utf8).GetAwaiter().GetResult()
        $warnings = @(& $candidate -Message 'Oversized file silenced' -WorkspaceRoot $fixture -MaxChangedFileSize 100 -NoCommitFileSnifferWarning 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
        if (@($warnings | Where-Object { $_.Message -match '^CommitFileSniffer:' }).Count) { throw 'NoCommitFileSnifferWarningDidNotSilenceIt' }

        # Dotfiles are hidden on Unix. Inspect them even when Get-Item requires -Force.
        foreach ($name in @('.hidden.bin', '.hidden-é.bin')) {
            $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
            $hidden = Join-Path $fixture $name
            [IO.File]::WriteAllBytes($hidden, [byte[]]@(66, 0, 67))
            if ($IsWindows) { [IO.File]::SetAttributes($hidden, [IO.FileAttributes]::Hidden) }
            $warnings = @(& $candidate -Message 'Hidden binary' -WorkspaceRoot $fixture 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
            if (@($warnings | Where-Object { $_.Message.StartsWith('CommitFileSniffer: ' + $name + ' (binary content)') }).Count -ne 1) { throw 'CommitFileSnifferBinaryWarningMissing' }
        }

        # G2 (property): the sniffer warns iff a changed file is binary or exceeds the threshold,
        # across randomly generated sizes and byte patterns.
        $random = [Random]::new(260779)
        for ($round = 0; $round -lt 10; $round++) {
            $fixture = New-QuietCommitWorkspaceFixture -Root $fixtureRoot -RealScriptsPath $realScripts
            $threshold = 50
            $isBinary = ($round % 2) -eq 0
            $size = if ($round -lt 5) { $random.Next(10, $threshold - 1) } else { $random.Next($threshold + 1, $threshold + 40) }
            $bytes = [byte[]]::new($size)
            $random.NextBytes($bytes)
            if ($isBinary) { $bytes[0] = 0 } else { for ($i = 0; $i -lt $bytes.Length; $i++) { if ($bytes[$i] -eq 0) { $bytes[$i] = 65 } } }
            $name = 'property' + $round + '.dat'
            [void][IO.File]::WriteAllBytesAsync((Join-Path $fixture $name), $bytes).GetAwaiter().GetResult()
            $expectWarning = $isBinary -or $size -gt $threshold
            $warnings = @(& $candidate -Message 'Sniffer property round' -WorkspaceRoot $fixture -MaxChangedFileSize $threshold 3>&1 | Where-Object { $_ -is [Management.Automation.WarningRecord] })
            $matching = @($warnings | Where-Object { $_.Message -match [regex]::Escape($name) })
            if ($expectWarning -and $matching.Count -ne 1) { throw ("CommitFileSnifferPropertyMissedExpectedWarning: seed=260779 round=$round size=$size isBinary=$isBinary") }
            if (!$expectWarning -and $matching.Count) { throw ("CommitFileSnifferPropertyFalsePositive: seed=260779 round=$round size=$size") }
        }
    }

    Test-QuietByteCountParsing

    if($CandidatePath){
        $null=& $verify $CandidatePath $fixtureRoot $realScripts $utf8
        return
    }

    & $verify $sourcePath $fixtureRoot $realScripts $utf8

    $mutants = @(
        @{Id = 'whatif-guard-removed-from-commit'; Find = 'if ($PSCmdlet.ShouldProcess($WorkspaceRoot, "git commit -m <message>")) {'; Replace = 'if ($true) {' },
        @{Id = 'whatif-guard-removed-from-add'; Find = 'if (!$NoAll -and $PSCmdlet.ShouldProcess($WorkspaceRoot, "git add --all --")) {'; Replace = 'if ($true) {' },
        @{Id = 'sync-gate-skipped-unconditionally'; Find = 'if (!$NoAll) { Invoke-QuietCommitChecks -Root $WorkspaceRoot }'; Replace = 'if ($false) { Invoke-QuietCommitChecks -Root $WorkspaceRoot }' },
        @{Id = 'drift-detection-disabled'; Find = 'if ($ChangedPaths -notcontains $docRelative) {'; Replace = 'if ($false) {' },
        @{Id = 'drift-override-ignored'; Find = 'if (!$NoScriptDocDriftWarning) {'; Replace = 'if ($true) {' },
        @{Id = 'noall-adds-working-tree'; Find = 'if (!$NoAll -and $PSCmdlet.ShouldProcess($WorkspaceRoot, "git add --all --")) {'; Replace = 'if ($PSCmdlet.ShouldProcess($WorkspaceRoot, "git add --all --")) {' },
        @{Id = 'noall-refreshes-working-lock'; Find = "if (!`$NoAll -and `$PSCmdlet.ShouldProcess(`$WorkspaceRoot, 'Refresh workspace lock (Update-WorkspaceLock.ps1)')) {"; Replace = "if (`$PSCmdlet.ShouldProcess(`$WorkspaceRoot, 'Refresh workspace lock (Update-WorkspaceLock.ps1)')) {" },
        @{Id = 'noall-skips-index-validation'; Find = 'if($NoAll){Assert-QuietStagedWorkspaceLock -WorkspaceRoot $WorkspaceRoot}'; Replace = 'if($false){Assert-QuietStagedWorkspaceLock -WorkspaceRoot $WorkspaceRoot}' },
        @{Id = 'file-sniffer-override-ignored'; Find = 'if (!$NoCommitFileSnifferWarning) {'; Replace = 'if ($false) {' },
        @{Id = 'file-sniffer-size-check-weakened'; Find = 'if ($isBinary -or $size -gt $MaxBytes) {'; Replace = 'if ($isBinary -and $size -gt $MaxBytes) {' },
        @{Id = 'file-sniffer-exemption-bypassed'; Find = "if (`$attr.Outcome -eq 'Success' -and @(`$attr.Data.Entries).Count -and `$attr.Data.Entries[0].Value -ceq 'set') { continue }"; Replace = "if (`$false) { continue }" }
    )
    foreach($mutant in $mutants){
        if (([regex]::Matches($source, [regex]::Escape($mutant.Find))).Count -ne 1) { throw ('CommitWorkspaceMutationAnchorInvalid: ' + $mutant.Id) }
    }
    $mutationWorker=Join-Path $PSScriptRoot 'CommitWorkspace.MutationWorker.ps1'
    # A zero native exit is not a completed mutation; preserve evidence even after an abrupt exit.
    $abruptDirectory=Join-Path $RunDirectory 'commit-workspace-worker-abrupt-exit'
    [void][IO.Directory]::CreateDirectory($abruptDirectory)
    $abruptCandidate=Join-Path $abruptDirectory candidate.ps1
    [IO.File]::WriteAllText($abruptCandidate,"param([string]`$Message,[string]`$WorkspaceRoot)`n[Environment]::Exit(0)`n",$utf8)
    $abruptResult=Join-Path $abruptDirectory result.json
    $abrupt=Invoke-CiProcess -FilePath (Join-Path $PSHOME $(if($IsWindows){'pwsh.exe'}else{'pwsh'})) -WorkingDirectory $WorkspaceRoot -TimeoutSeconds 120 -ArgumentList @('-NonInteractive','-File',$mutationWorker,'-WorkspaceRoot',$WorkspaceRoot,'-RunDirectory',$abruptDirectory,'-CandidatePath',$abruptCandidate,'-ResultPath',$abruptResult,'-WhatIf:$false','-Confirm:$false') -OnOutput {param($event,$state)}
    if($abrupt.Outcome -cne 'Success' -or !(Test-Path -LiteralPath $abruptResult)){throw 'MutationAbruptWorkerFixtureFailed'}
    $unfinished=Get-Content -LiteralPath $abruptResult -Raw -Encoding utf8|ConvertFrom-Json
    if($unfinished.State -cne 'InfrastructureFailure' -or $unfinished.Stage -ceq 'Completed'){throw 'MutationZeroExitAcceptedAsCompletion'}
    $parallelResults=@($mutants | ForEach-Object -ThrottleLimit $MaxConcurrency -Parallel {
        $mutant=$_
        try {
            $workerScripts=$using:realScripts
            $workerMutationWorker=$using:mutationWorker
            $workerWorkspaceRoot=$using:WorkspaceRoot
            $workerRunDirectory=$using:RunDirectory
            $workerSource=$using:source
            Import-Module ([IO.Path]::Combine($workerScripts,'lib/Ci.Process.psm1')) -DisableNameChecking -ErrorAction Stop
            $workerUtf8=[Text.UTF8Encoding]::new($false)
            $candidateDirectory=Join-Path $workerRunDirectory ('commit-workspace-mutant-'+$mutant.Id)
            [void][IO.Directory]::CreateDirectory($candidateDirectory)
            # Keep the real dependency layout: a missing Common.ps1 must never count as a killed mutant.
            Get-ChildItem -LiteralPath $workerScripts -Force|Copy-Item -Destination $candidateDirectory -Recurse -Force
            $candidatePath=Join-Path $candidateDirectory 'Commit-Workspace.ps1'
            $candidateLibrary=[IO.Path]::Combine($candidateDirectory,'lib/Commit-Workspace.psm1')
            # The candidate owns automation sources; its informational sniffer uses the real built modules.
            # Bind that dependency explicitly rather than pretending the sandbox is a product distribution.
            $candidateSource=$workerSource.Replace($mutant.Find,$mutant.Replace)
            $candidateSource=$candidateSource.Replace('$moduleRoot = Split-Path ([IO.Path]::GetDirectoryName($PSScriptRoot)) -Parent',('$moduleRoot = '+"'"+$workerWorkspaceRoot.Replace("'","''")+"'"))
            [void][IO.File]::WriteAllTextAsync($candidateLibrary,$candidateSource,$workerUtf8).GetAwaiter().GetResult()
            $tokens=$null;$errors=$null;$null=[Management.Automation.Language.Parser]::ParseFile($candidateLibrary,[ref]$tokens,[ref]$errors)
            if($errors.Count){throw ('CommitWorkspaceMutantInvalid: '+$mutant.Id)}
            $resultPath=Join-Path $candidateDirectory 'result.json'
            $processState=@{Lines=0;Tail=[Collections.Generic.Queue[string]]::new()}
            $runner=Join-Path $PSHOME $(if($IsWindows){'pwsh.exe'}else{'pwsh'})
            $process=Invoke-CiProcess -FilePath $runner -ArgumentList @('-NonInteractive','-File',$workerMutationWorker,'-WorkspaceRoot',$workerWorkspaceRoot,'-RunDirectory',$candidateDirectory,'-CandidatePath',$candidatePath,'-ResultPath',$resultPath,'-WhatIf:$false','-Confirm:$false') -WorkingDirectory $workerWorkspaceRoot -TimeoutSeconds 900 -State $processState -OnOutput {
                param($event,$state)
                $state.Lines++
                $text=[string]$event.Text
                $state.Tail.Enqueue($text.Substring(0,[Math]::Min(512,$text.Length)))
                if($state.Tail.Count -gt 16){[void]$state.Tail.Dequeue()}
            }
            $diagnostic=@{Name=$mutant.Id;Outcome=$process.Outcome;ExitCode=$process.ExitCode;ObservedLines=$processState.Lines;Tail=@($processState.Tail);ResultExists=(Test-Path -LiteralPath $resultPath)}
            [IO.File]::WriteAllText((Join-Path $candidateDirectory 'worker-process.json'),($diagnostic|ConvertTo-Json -Depth 4)+"`n",$workerUtf8)
            if($process.Outcome -ne 'Success' -or !$diagnostic.ResultExists){throw ('CommitWorkspaceMutationWorkerFailed: '+$mutant.Id+': '+$process.Outcome+'/'+$process.ExitCode+'; diagnostic='+$candidateDirectory+'/worker-process.json')}
            $receipt=Get-Content -LiteralPath $resultPath -Raw -Encoding utf8|ConvertFrom-Json
            if($receipt.Name -cne $mutant.Id -or $receipt.Stage -cne 'Completed' -or $receipt.State -cnotin @('Killed','Survived')){throw ('CommitWorkspaceMutationWorkerIncomplete: '+$mutant.Id+'; diagnostic='+$candidateDirectory+'/worker-process.json')}
            $receipt
        }catch{
            [pscustomobject]@{Name=$mutant.Id;State='InfrastructureFailure';Diagnostic=$_.Exception.Message}
        }
    })
    $results=[Collections.Generic.List[object]]::new()
    foreach($mutant in $mutants){
        $result=@($parallelResults|Where-Object Name -CEQ $mutant.Id)
        if($result.Count -ne 1){throw ('CommitWorkspaceMutantResultMissing: '+$mutant.Id)}
        $detail=$result[0].Diagnostic
        if($result[0].State -eq 'InfrastructureFailure' -or ($result[0].State -eq 'Killed' -and $detail -notmatch '^(WhatIfMustNotCommit|WhatIfMustNotStage|WhatIfAttemptedNativeMutation|MissingScriptDocGateDidNotBlock|ScriptDocDriftWarningMissing|NoScriptDocDriftWarningDidNotSilenceIt|NoAllIncludedUnstagedContent|NoAllIncludedUnselectedFile|NoAllWorkingTreeLockChanged|NoAllEmptyIndexAccepted|NoAllDamagedLockAcceptedOrIndexChanged|CommitFileSnifferBinaryWarningMissing|CommitFileSnifferMustNotBlockCommit|CommitFileSnifferExemptionBypassed|CommitFileSnifferSizeWarningMissing|NoCommitFileSnifferWarningDidNotSilenceIt|CommitFileSnifferPropertyMissedExpectedWarning|CommitFileSnifferPropertyFalsePositive)')){
            throw ('CommitWorkspaceMutantInfrastructureFailure: '+$mutant.Id+': '+$detail)
        }
        $results.Add($result[0])
        if($result[0].State -ne 'Killed'){throw ('CommitWorkspaceMutantSurvived: '+$mutant.Id)}
    }
    $report = @{
        TestKind          = 'Integration'
        Dependencies      = @('FileSystem','GitProcess')
        FixtureStorage    = 'PhysicalTemporaryDirectory'
        Seed              = 97120
        PropertyExecutions = 25
        FuzzInputs        = 10
        MaxConcurrency    = $MaxConcurrency
        Mutations         = $results.ToArray()
        SourceSHA256      = (Get-FileHash $sourcePath -Algorithm SHA256).Hash
        Scope             = "Documentation-sync gate wiring, script/doc drift detection, the binary/oversized-file sniffer and the -WhatIf/commit-once/no-remote contract against disposable fixture repositories; the three Sync-*.ps1 gates' own internal correctness is not re-verified here."
    }
    Write-WorkspaceJson (Join-Path $RunDirectory 'commit-workspace.json') $report
    [pscustomobject]$report
}
